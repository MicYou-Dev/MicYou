fn dict_for(lang: &str) -> &'static Dict {
    match lang {
        "en" => &EN,
        "cat" => &CAT,
        "lzh" => &LZH,
        "zh-hk" => &ZH_HK,
        "zh-ss" => &ZH_SS,
        "zh-tw" => &ZH_TW,
        _ => &ZH,
    }
}

/// Look up a translation; falls back to zh, then to the key itself.
pub fn tr(lang: &str, key: &str) -> String {
    let dict = dict_for(lang);
    for (k, v) in dict.entries {
        if *k == key {
            return (*v).to_string();
        }
    }
    let zh = dict_for("zh");
    for (k, v) in zh.entries {
        if *k == key {
            return (*v).to_string();
        }
    }
    key.to_string()
}
